const normalise = (value) => String(value || "").toLowerCase().replace(/[^a-z0-9]+/g," ").trim();

export function findGrainsInText(value) {
  const text = ` ${normalise(value)} `;
  return grainNutritionData.filter((grain) =>
    grain.aliases.some((alias) => text.includes(` ${normalise(alias)} `)),
  );
}

export function getGrainById(id) {
  return grainNutritionData.find((grain) => grain.id === id) || null;
}

